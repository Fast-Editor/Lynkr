/**
 * TencentDB-Agent-Memory Sidecar Launcher
 *
 * Launches the TencentDB-Agent-Memory stack (memory-core gateway +
 * memory-hub panel/knowledge services) via dockerode when
 * TENCENTDB_MEMORY_ENABLED=true — the same in-process pattern as the
 * Headroom sidecar launcher, extended to a two-container stack.
 *
 * Mirrors the project's own deploy/global-images/start-*.sh scripts:
 *  - shared docker network `tdai-memory-stack` with service aliases
 *  - memory-core config generated locally and mounted read-only
 *  - first-boot admin user init, key persisted to data/tencentdb-memory/
 *
 * The memory services need an LLM for extraction/summarization; by default
 * that points back at Lynkr's own OpenAI-compatible endpoint, so the whole
 * stack runs on whatever providers Lynkr already has.
 *
 * Containers use restart=unless-stopped and are intentionally NOT stopped
 * when Lynkr exits — a team memory hub outlives any one proxy process.
 * Remove with: docker rm -f tdai-memory-core tdai-memory-hub
 */

let Docker;
try {
  Docker = require("dockerode");
} catch {
  Docker = null;
}
const path = require("path");
const fs = require("fs");
const crypto = require("crypto");
const logger = require("../logger");
const config = require("../config");

const docker = Docker ? new Docker() : null;

const DATA_DIR = path.join(process.cwd(), "data", "tencentdb-memory");
const ADMIN_KEY_FILE = path.join(DATA_DIR, ".admin-key");
const CORE_CONFIG_FILE = path.join(DATA_DIR, "tdai-gateway.yaml");

let isStarting = false;

function sidecarConfig() {
  return config.tencentdbMemory ?? {};
}

